import json
import shutil
from pathlib import Path
from uuid import uuid4

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from career_agent.database.models import AuditLog, Job, ResumeVersion, WorkflowRun, now
from career_agent.database.repository import save_profile
from career_agent.documents.export import export_documents
from career_agent.documents.tailoring import DocumentError, select_claims
from career_agent.models.job import JobPosting


def prepare_documents(engine, profile, job_id, root: Path, *, use_ai=False):
    import hashlib
    import re

    if not job_id or not re.fullmatch(r"[A-Za-z0-9_-]{1,64}", job_id):
        raise DocumentError("invalid_job_id")

    with Session(engine) as session:
        job = session.get(Job, job_id)
        if job is None or not job.payload.get("posting"):
            raise DocumentError("job_not_found")
        posting = JobPosting.model_validate(job.payload["posting"])
        version = (
            session.scalar(
                select(func.max(ResumeVersion.version)).where(
                    ResumeVersion.candidate_id == profile.candidate_id,
                    ResumeVersion.job_id == job_id,
                )
            )
            or 0
        ) + 1
    output = root / "data/resumes" / profile.candidate_id / job_id / f"{version}-{uuid4().hex}"
    try:
        selection = select_claims(profile, posting, use_ai=use_ai)
        manifest = export_documents(profile, posting, selection, output)
        digest = hashlib.sha256(json.dumps(manifest, sort_keys=True).encode()).hexdigest()
        with Session(engine) as session, session.begin():
            save_profile(session, profile)
            record = ResumeVersion(
                candidate_id=profile.candidate_id,
                job_id=job_id,
                version=version,
                document_path=str(output.relative_to(root)),
                content_sha256=digest,
                claim_ids=manifest["claim_ids"],
            )
            run = WorkflowRun(
                kind="document_generation",
                status="SUCCEEDED",
                finished_at=now(),
                summary={"version": version, "verified_claims": len(manifest["claim_ids"])},
            )
            session.add_all([record, run])
            session.flush()
            session.add(
                AuditLog(
                    run_id=run.id,
                    action="DOCUMENTS_VALIDATED",
                    details={"resume_id": record.id, "version": version},
                )
            )
            record_id = record.id
        return {
            "resume_id": record_id,
            "version": version,
            "document_path": str(output.relative_to(root)),
            "ats_validated": True,
        }
    except FileExistsError as exc:
        raise DocumentError("output_already_exists") from exc
    except Exception:
        if output.exists():
            shutil.rmtree(output)  # Unique directory generated by this operation only.
        raise
